export const getTranslation = (lang = 'id', key) => {
  const currentLangDict = DICTIONARY[lang] || DICTIONARY.id;
  if (currentLangDict && key in currentLangDict) {
    return currentLangDict[key];
  }
  if (DICTIONARY.id && key in DICTIONARY.id) {
    return DICTIONARY.id[key];
  }
  return key;
};

export const getCategoryName = (categoryNameOrObj, lang = 'id') => {
  if (!categoryNameOrObj) return '';
  const rawName = typeof categoryNameOrObj === 'string' 
    ? categoryNameOrObj 
    : (categoryNameOrObj.name || categoryNameOrObj.category || categoryNameOrObj.categoryId || categoryNameOrObj.title || '');
  
  if (CATEGORY_TRANSLATIONS[lang]) {
    if (CATEGORY_TRANSLATIONS[lang][rawName]) {
      return CATEGORY_TRANSLATIONS[lang][rawName];
    }
    const lower = rawName.toLowerCase();
    if (CATEGORY_TRANSLATIONS[lang][lower]) {
      return CATEGORY_TRANSLATIONS[lang][lower];
    }
  }
  return rawName;
};
